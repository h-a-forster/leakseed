"""How often does the scorecard's 95% cluster-bootstrap interval cover, with 30 templates?

A double-bootstrap calibration check. Its world: templates are exchangeable draws from the 30
templates of corpus v1, each with the outcomes the tool actually has on its files, so the true
pooled rate is the observed one. Each simulated study draws 30 templates with replacement and
computes the same percentile interval as the scorecard (stats.cluster_bootstrap). The share of
studies whose interval holds the true rate is that interval's coverage in this world. Writes
results/v1/bootstrap_coverage.md.
"""

from __future__ import annotations

from pathlib import Path

import numpy as np

from leakseed.adapters import ADAPTERS, get
from leakseed.generate import read_manifest
from leakseed.score import file_outcomes, read_findings, site_hit
from leakseed.stats import clopper_pearson, cluster_bootstrap

ROOT = Path(__file__).resolve().parents[1]
V1, RESULTS = ROOT / "corpus" / "v1", ROOT / "results" / "v1"
OUT = RESULTS / "bootstrap_coverage.md"
STUDIES, N_BOOT, SEED = 2000, 2000, 0


def coverage(y: np.ndarray, g: np.ndarray, rng: np.random.Generator) -> tuple[int, int]:
    """Studies whose interval covers the observed pooled rate, and studies run."""
    truth = y.mean()
    labels = np.unique(g)
    members = [np.flatnonzero(g == c) for c in labels]
    hits = 0
    for i in range(STUDIES):
        drawn = rng.integers(len(labels), size=len(labels))
        idx = np.concatenate([members[d] for d in drawn])
        # Relabel so a template drawn twice counts as two clusters, as two fresh templates would.
        groups = np.concatenate([np.full(len(members[d]), j) for j, d in enumerate(drawn)])
        _, lo, hi = cluster_bootstrap(y[idx], groups, n_boot=N_BOOT, seed=SEED + i)
        hits += lo <= truth <= hi
    return hits, STUDIES


def main() -> None:
    manifest = read_manifest(V1)
    leak = [r for r in manifest if r["label"] == "leak"]
    g = np.array([r["template"] for r in leak])
    rng = np.random.default_rng(SEED)
    out = [
        "# Coverage of the 95% cluster-bootstrap interval (paired at the site)",
        "",
        "Generated by `scripts/bootstrap_coverage.py`. In a world where templates are drawn "
        f"from the {len(set(g))} templates of v1 with their observed outcomes, {STUDIES} "
        f"simulated studies each compute the scorecard's percentile interval ({N_BOOT} "
        "resamples). Coverage is the share that hold the true pooled rate, with a "
        "Clopper-Pearson 95% interval over the studies. Tools with no hit are left out: every "
        "interval is then [0, 0] and covers trivially.",
        "",
        "| Tool | Rate | Coverage of the nominal 95% |",
        "|---|---|---|",
    ]
    for name in ADAPTERS:
        adapter = get(name)
        outcomes = file_outcomes(manifest, read_findings(RESULTS / "findings" / f"{name}.jsonl"),
                                 adapter)  # fmt: skip
        y = np.array([site_hit(outcomes, r) for r in leak], dtype=float)
        if not y.any():
            continue
        k, n = coverage(y, g, rng)
        lo, hi = clopper_pearson(k, n)
        out.append(
            f"| {name} | {100 * y.mean():.1f}% | {100 * k / n:.1f}% "
            f"[{100 * lo:.1f}, {100 * hi:.1f}] |"
        )
        print(out[-1], flush=True)
    OUT.write_text("\n".join(out) + "\n", encoding="utf-8", newline="\n")
    print(f"wrote {OUT}")


if __name__ == "__main__":
    main()
