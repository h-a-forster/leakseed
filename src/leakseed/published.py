"""The tables and headline prose that README.md and REPORT.md publish, rendered from summary.json.

`leakseed report` writes them to `published.md` beside the scorecard. A test checks that every
numeric table row in README.md and REPORT.md is a line of that file, and that the README's
generated block is a copy of it, so a published number cannot drift from the results.
"""

from __future__ import annotations

import textwrap

from .templates import LEVELS

BASELINE = "ruff-defaults"
LABELS = {
    "monte-neo": "monte-neo (lint only)",
    "leakguard": "leakguard (static core)",
    "overfit-gauntlet": "overfit-gauntlet (lint)",
    "ruff-defaults": "ruff defaults (null)",
}
MARKERS = (
    "<!-- headline: generated by `leakseed report` (results/v1/published.md); do not edit -->\n",
    "<!-- end of generated headline -->\n",
)
README_PROSE = """\
The *any linter* row means at least one tool on its own for each case, not the result of running
all seven and OR-ing their flags; the OR of all seven gives {merged_site}/{n} paired at the site
and {merged_paired}/{n} paired discrimination, against the row's {union_site} and the scorecard's
{union_paired}.

What stands out:

- **Noise.** {leader} leads every other tool at the site (Holm-adjusted template p from {p_lo} to
{p_hi}), but much of its recall is warnings on code both twins share. At its `{leader_top}`
severity alone its rates are {leader_strict_site} at the site and {leader_strict_fpr} false
positives.
- **Size.** {material} leaky files reach |Sharpe| >= {threshold:g} on drift-free data; the largest
clean twin reaches {max_clean}. No tool finds {material_missed} of the {material} at the site.
- **Coverage.** No tool finds {uncaught} at the site. These are gaps in form: PP010 fires once a
`signal * returns` line exists, three tools catch a negative `np.roll`, and four catch a
time-blind `GridSearchCV` ([results/v1/probes.md](results/v1/probes.md)).
- **Indirection.** {halved} of the seven tools lose more than half their score from L0 to L1, when
a value passes through one local variable. {leader} inlines constants and stays at
{leader_l1}/{per_level}. At L3 no tool separates the twins (0/{per_level} each).
- **Comparisons.** At the site, {site_mcnemar} of the {pairs} tool pairs pass p < 0.05 with
McNemar over files. Files of one template are correlated; {site_template} of {pairs} survive a
sign-flip test over templates with Holm. For recall the counts are {recall_mcnemar} and
{recall_template}.
"""

NUMBER_WORDS = {2: "Two", 3: "Three", 4: "Four", 5: "Five", 6: "Six", 7: "Seven"}


def _fmt(e: dict) -> str:
    if e["k"] == 0 and e["hi"] == 0:
        return f"0.0% ({e['k']}/{e['n']})"
    return f"{100 * e['rate']:.1f}% [{100 * e['lo']:.1f}, {100 * e['hi']:.1f}] ({e['k']}/{e['n']})"


def _short(e: dict) -> str:
    return f"{100 * e['rate']:.1f}% ({e['k']})"


def _version(v: str) -> str:
    return f"git {v.split('+', 1)[1]}" if "+" in v else v


def _p(p: float) -> str:
    return f"{p:.1g}" if p < 0.001 else f"{p:.2g}"


def _order(s: dict) -> list[str]:
    """Linters by paired-at-the-site hits, the measure to read; the null baseline last."""
    linters = [t for t in s["tools"] if t != BASELINE]
    return sorted(linters, key=lambda t: -s["tools"][t]["primary"]["paired_site"]["k"])


def tables(s: dict) -> list[str]:
    out = ["# Published tables", "",
           "Generated by `leakseed report` from summary.json: README.md and REPORT.md copy these "
           "rows.", ""]  # fmt: skip
    order = _order(s)
    tools = s["tools"]
    out += ["## README: headline scorecard", ""]
    out += ["| Tool | Version | Paired at the site | Recall | False-positive rate |",
            "|---|---|---|---|---|"]  # fmt: skip
    for t in [*order, BASELINE]:
        p = tools[t]["primary"]
        out.append(
            f"| {LABELS.get(t, t)} | {_version(tools[t]['version'])} | {_fmt(p['paired_site'])} | "
            f"{_fmt(p['recall'])} | {_fmt(p['fpr'])} |"
        )
    u = s["union"]
    out.append(
        f"| any linter | - | {_fmt(u['paired_site'])} | {_fmt(u['recall'])} | {_fmt(u['fpr'])} |"
    )

    out += ["", "## REPORT: headline", ""]
    out += ["| Tool | Paired at the site | Recall | False-positive rate |", "|---|---|---|---|"]
    for t in [*order, BASELINE]:
        p = tools[t]["primary"]
        name = "ruff defaults (null)" if t == BASELINE else f"{t} {_version(tools[t]['version'])}"
        name = name.replace(" git ", " ")
        site = _short(p["paired_site"]) if t == BASELINE else _fmt(p["paired_site"])
        site = site.replace(f"/{p['paired_site']['n']})", ")")
        out.append(f"| {name} | {site} | {_short(p['recall'])} | {_short(p['fpr'])} |")
    site = _fmt(u["paired_site"]).replace(f"/{u['paired_site']['n']})", ")")
    out.append(f"| any linter | {site} | {_short(u['recall'])} | {_short(u['fpr'])} |")

    out += ["", "## REPORT: paired at the site by obfuscation level", ""]
    out += ["| Tool | " + " | ".join(LEVELS) + " |", "|---" * (len(LEVELS) + 1) + "|"]
    for t in order:
        by = tools[t]["paired_site_by_level"]
        out.append(f"| {t} | " + " | ".join(str(by[lvl]["k"]) for lvl in LEVELS) + " |")

    out += ["", "## REPORT: size of the leak", ""]
    out += ["| Class | Median leaky | Material | Found at the site |", "|---|---|---|---|"]
    classes = s["impact"]["classes"]
    material = [c for c in classes if classes[c]["material"]]
    for c in sorted(material, key=lambda c: -classes[c]["median_abs_leaky"]):
        x = classes[c]
        out.append(
            f"| {c} | {x['median_abs_leaky']:.2f} | {x['material']}/{x['pairs']} | "
            f"{x['material_found']}/{x['material']} |"
        )
    return out


def readme_block(s: dict) -> str:
    tools, order = s["tools"], _order(s)
    leader = order[0]
    lead = tools[leader]
    vs = [
        x
        for x in s["mcnemar"]
        if x["measure"] == "paired at the site" and leader in (x["a"], x["b"])
    ]
    if not all(x["p_cluster_holm"] < 0.05 for x in vs):
        raise ValueError(f"{leader} no longer leads every tool at the site")
    holm = [x["p_cluster_holm"] for x in vs]
    by_measure = {
        m: [x for x in s["mcnemar"] if x["measure"] == m] for m in ("paired at the site", "recall")
    }
    site, recall = by_measure["paired at the site"], by_measure["recall"]
    levels = {t: tools[t]["paired_site_by_level"] for t in order}
    halved = sum(lv["L1"]["k"] < lv["L0"]["k"] / 2 for lv in levels.values())
    if any(lv["L3"]["k"] for lv in levels.values()):
        raise ValueError("a tool now separates the twins at L3")
    if levels[leader]["L1"]["k"] != levels[leader]["L0"]["k"]:
        raise ValueError(f"{leader} no longer holds its score from L0 to L1")
    impact = s["impact"]
    uncaught = [f"`{c}`" for c in s["coverage"]["uncaught_classes"]]
    merged, union = s["merged"], s["union"]
    values = {
        "n": merged["n"],
        "merged_site": merged["paired_site"],
        "merged_paired": merged["paired"],
        "union_site": union["paired_site"]["k"],
        "union_paired": union["paired"]["k"],
        "leader": leader,
        "p_lo": _p(min(holm)),
        "p_hi": _p(max(holm)),
        "leader_top": lead["top_severity"],
        "leader_strict_site": f"{100 * lead['strict']['paired_site']['rate']:.1f}%",
        "leader_strict_fpr": f"{100 * lead['strict']['fpr']['rate']:.1f}%",
        "material": impact["material_pairs"],
        "threshold": impact["threshold"],
        "max_clean": f"{impact['max_abs_clean']:.2f}",
        "material_missed": impact["material_pairs"] - impact["material_found_by_any"],
        "uncaught": ", ".join(uncaught[:-1]) + " or " + uncaught[-1],
        "halved": NUMBER_WORDS[halved],
        "leader_l1": levels[leader]["L1"]["k"],
        "per_level": levels[leader]["L1"]["n"],
        "pairs": len(site),
        "site_mcnemar": sum(x["p"] < 0.05 for x in site),
        "site_template": sum(x["p_cluster_holm"] < 0.05 for x in site),
        "recall_mcnemar": sum(x["p"] < 0.05 for x in recall),
        "recall_template": sum(x["p_cluster_holm"] < 0.05 for x in recall),
    }
    text = README_PROSE.format(**values)
    paragraphs = []
    for para in text.strip("\n").split("\n\n"):
        if para.startswith("- "):
            items = [" ".join(i.split()) for i in para.split("\n- ")]
            items = [i if i.startswith("- ") else "- " + i for i in items]
            wrap = textwrap.TextWrapper(96, subsequent_indent="  ", break_on_hyphens=False)
            paragraphs.append("\n".join(wrap.fill(i) for i in items))
        else:
            paragraphs.append(textwrap.fill(" ".join(para.split()), 96, break_on_hyphens=False))
    start, end = MARKERS
    return start + "\n\n".join(paragraphs) + "\n" + end


def render(s: dict) -> str:
    out = tables(s)
    out += ["", "## README: headline prose", "", readme_block(s).rstrip("\n")]
    return "\n".join(out) + "\n"


def sync_readme(readme_text: str, block: str) -> str:
    start, end = MARKERS
    if (
        readme_text.count(start) != 1
        or readme_text.count(end) != 1
        or readme_text.index(start) > readme_text.index(end)
    ):
        raise ValueError("README.md needs exactly one block between the generated markers")
    head, rest = readme_text.split(start)
    return head + block + rest.split(end)[1]
