NUMBER_WORDS = {
    1: "One", 2: "Two", 3: "Three", 4: "Four", 5: "Five", 6: "Six", 7: "Seven", 8: "Eight",
    9: "Nine", 10: "Ten", 11: "Eleven", 12: "Twelve",
}  # fmt: skip


def _fmt(e: dict) -> str:
    if e["k"] == 0 and e["hi"] == 0:
        return f"0.0% ({e['k']}/{e['n']})"
    return f"{100 * e['rate']:.1f}% [{100 * e['lo']:.1f}, {100 * e['hi']:.1f}] ({e['k']}/{e['n']})"


def _short(e: dict) -> str:
    return f"{100 * e['rate']:.1f}% ({e['k']})"


def _version(v: str) -> str:
    return f"git {v.split('+', 1)[1]}" if "+" in v else v


def _p(p: float) -> str:
    return f"{p:.1g}" if p < 0.001 else f"{p:.2g}"


def _order(s: dict) -> list[str]:
    """Linters by paired-at-the-site hits, the measure to read; the null baseline last."""
    linters = [t for t in s["tools"] if t != BASELINE]
    return sorted(linters, key=lambda t: -s["tools"][t]["primary"]["paired_site"]["k"])


def tables(s: dict) -> list[str]:
    out = ["# Published tables", "",
           "Generated by `leakseed report` from summary.json: README.md and REPORT.md copy these "
           "rows.", ""]  # fmt: skip
    order = _order(s)
    tools = s["tools"]
    out += ["## README: headline scorecard", ""]
    out += ["| Tool | Version | Paired at the site | Recall | False-positive rate |",
            "|---|---|---|---|---|"]  # fmt: skip
    for t in [*order, BASELINE]:
        p = tools[t]["primary"]
        out.append(
            f"| {LABELS.get(t, t)} | {_version(tools[t]['version'])} | {_fmt(p['paired_site'])} | "
            f"{_fmt(p['recall'])} | {_fmt(p['fpr'])} |"
        )
    u = s["union"]
    out.append(
        f"| any linter | - | {_fmt(u['paired_site'])} | {_fmt(u['recall'])} | {_fmt(u['fpr'])} |"
    )

    out += ["", "## REPORT: headline", ""]
    out += ["| Tool | Paired at the site | Recall | False-positive rate |", "|---|---|---|---|"]
    for t in [*order, BASELINE]:
        p = tools[t]["primary"]
        name = "ruff defaults (null)" if t == BASELINE else f"{t} {_version(tools[t]['version'])}"
        name = name.replace(" git ", " ")
        site = _short(p["paired_site"]) if t == BASELINE else _fmt(p["paired_site"])
        site = site.replace(f"/{p['paired_site']['n']})", ")")
        out.append(f"| {name} | {site} | {_short(p['recall'])} | {_short(p['fpr'])} |")
    site = _fmt(u["paired_site"]).replace(f"/{u['paired_site']['n']})", ")")
    out.append(f"| any linter | {site} | {_short(u['recall'])} | {_short(u['fpr'])} |")

    out += ["", "## REPORT: paired at the site by obfuscation level", ""]
    out += ["| Tool | " + " | ".join(LEVELS) + " |", "|---" * (len(LEVELS) + 1) + "|"]
    for t in order:
        by = tools[t]["paired_site_by_level"]
        out.append(f"| {t} | " + " | ".join(str(by[lvl]["k"]) for lvl in LEVELS) + " |")

    out += ["", "## REPORT: size of the leak", ""]
    out += ["| Class | Median leaky | Material | Found at the site |", "|---|---|---|---|"]
    classes = s["impact"]["classes"]
    material = [c for c in classes if classes[c]["material"]]
    for c in sorted(material, key=lambda c: -classes[c]["median_abs_leaky"]):
        x = classes[c]
        out.append(
            f"| {c} | {x['median_abs_leaky']:.2f} | {x['material']}/{x['pairs']} | "
            f"{x['material_found']}/{x['material']} |"
        )
    return out


def _values(s: dict) -> dict:
    """The figures both proses quote; raises when the results no longer support a sentence."""
    tools, order = s["tools"], _order(s)
    leader = order[0]
    lead = tools[leader]
    vs = [
        x
        for x in s["mcnemar"]
        if x["measure"] == "paired at the site" and leader in (x["a"], x["b"])
    ]
    if not all(x["p_cluster_holm"] < 0.05 for x in vs):
        raise ValueError(f"{leader} no longer leads every tool at the site")
    holm = [x["p_cluster_holm"] for x in vs]
    by_measure = {
        m: [x for x in s["mcnemar"] if x["measure"] == m] for m in ("paired at the site", "recall")
    }
    site, recall = by_measure["paired at the site"], by_measure["recall"]
    levels = {t: tools[t]["paired_site_by_level"] for t in order}
    halved = sum(lv["L1"]["k"] < lv["L0"]["k"] / 2 for lv in levels.values())
    if any(lv["L3"]["k"] for lv in levels.values()):
        raise ValueError("a tool now separates the twins at L3")
    if levels[leader]["L1"]["k"] != levels[leader]["L0"]["k"]:
        raise ValueError(f"{leader} no longer holds its score from L0 to L1")
    impact = s["impact"]
    uncaught = [f"`{c}`" for c in s["coverage"]["uncaught_classes"]]
    merged, union = s["merged"], s["union"]
    return {
        "n": merged["n"],
        "merged_site": merged["paired_site"],
        "merged_paired": merged["paired"],
        "union_site": union["paired_site"]["k"],
        "union_paired": union["paired"]["k"],
        "leader": leader,
        "p_lo": _p(min(holm)),
        "p_hi": _p(max(holm)),
        "leader_top": lead["top_severity"],
        "leader_strict_site": f"{100 * lead['strict']['paired_site']['rate']:.1f}%",
        "leader_strict_fpr": f"{100 * lead['strict']['fpr']['rate']:.1f}%",
        "material": impact["material_pairs"],
        "threshold": impact["threshold"],
        "max_clean": f"{impact['max_abs_clean']:.2f}",
        "material_missed": impact["material_pairs"] - impact["material_found_by_any"],
        "uncaught": ", ".join(uncaught[:-1]) + " or " + uncaught[-1],
        "halved": NUMBER_WORDS[halved],
        "leader_l1": levels[leader]["L1"]["k"],
        "per_level": levels[leader]["L1"]["n"],
        "pairs": len(site),
        "site_mcnemar": sum(x["p"] < 0.05 for x in site),
        "site_template": sum(x["p_cluster_holm"] < 0.05 for x in site),
        "recall_mcnemar": sum(x["p"] < 0.05 for x in recall),
        "recall_template": sum(x["p_cluster_holm"] < 0.05 for x in recall),
    }


def _join(items: list[str]) -> str:
    return items[0] if len(items) == 1 else ", ".join(items[:-1]) + " and " + items[-1]


def _p3(p: float) -> str:
    return f"{p:.4f}" if p < 0.001 else f"{p:.3f}"


def report_figures(s: dict) -> list[str]:
    """Every sentence of REPORT.md's prose that quotes a result, rendered from the summary."""
    tools, order = s["tools"], _order(s)
    v = _values(s)
    lead = tools[v["leader"]]
    primary = {t: tools[t]["primary"] for t in order}
    impact, classes = s["impact"], s["impact"]["classes"]
    unfound = s["coverage"]["uncaught_classes"]

    def detail(c: str) -> str:
        x = classes[c]
        if x["material"] == x["pairs"]:
            return f"`{c}` (0/{x['pairs']}, and all {x['pairs']} are material)"
        return f"`{c}`"

    modes = s["oracle"]["leak_witness_modes"]
    if set(modes) != {"values", "availability"}:
        raise ValueError("the leak witnesses are no longer only values and availability")
    graded = [t for t in order if tools[t]["top_severity"]]
    graded.sort(key=lambda t: -tools[t]["strict"]["paired_site"]["k"])
    strict = [
        f"{t} " + " / ".join(f"{100 * tools[t]['strict'][m]['rate']:.1f}"
                             for m in ("recall", "fpr", "paired_site"))
        for t in graded
    ]  # fmt: skip
    by_mean = sorted(order, key=lambda t: -primary[t]["paired_site_class_mean"])[:3]
    site = [x for x in s["mcnemar"] if x["measure"] == "paired at the site"]
    wins: dict[str, list[tuple[float, str]]] = {}
    for x in site:
        if x["p_cluster_holm"] < 0.05:
            winner, loser = (x["a"], x["b"]) if x["only_a"] > x["only_b"] else (x["b"], x["a"])
            wins.setdefault(winner, []).append((x["p_cluster_holm"], loser))
    beats = [
        f"{w} beats " + _join([f"{loser} ({_p3(p)})" for p, loser in sorted(wins[w])]) + "."
        for w in sorted(wins, key=lambda w: (-len(wins[w]), order.index(w)))
    ]
    gap = min((x for x in site if x["p_cluster_holm"] >= 0.05), key=lambda x: x["p"])
    l3 = {t: tools[t]["fpr_by_level"]["L3"] for t in order}
    restated = {t: tools[t]["paired_site_by_class"]["restatement_overwrite"] for t in order}
    restated = {t: e for t, e in restated.items() if e["k"]}
    if len(restated) != 1:
        raise ValueError("restatement_overwrite is no longer found by exactly one tool")
    (restatement_tool, restatement), = restated.items()  # fmt: skip
    found = impact["material_found_by_tool"]
    exact = {t: primary[t]["localisation_exact"] for t in order}
    inexact = [f"{e['k']}/{e['n']} for {t}" for t, e in exact.items() if e["k"] != e["n"]]
    chance = [100 * primary[t]["localisation_chance"] for t in order]
    values = {
        **v,
        "leader_version": _version(lead["version"]),
        "leader_site": _fmt(lead["primary"]["paired_site"]),
        "leader_recall": f"{100 * lead['primary']['recall']['rate']:.1f}%",
        "leader_fpr": f"{100 * lead['primary']['fpr']['rate']:.1f}%",
        "union_site_full": _fmt(s["union"]["paired_site"]),
        "n_tools": NUMBER_WORDS[len(order)].lower(),
        "n_uncaught": NUMBER_WORDS[len(unfound)],
        "uncaught_detail": _join([detail(c) for c in unfound]),
        "uncaught_and": _join([f"`{c}`" for c in unfound]),
        "files": s["corpus"]["files"],
        "classes": s["corpus"]["classes"],
        "n_levels": len(s["corpus"]["levels"]),
        "libs": "/".join(s["corpus"]["libs"]),
        "templates": s["corpus"]["templates"],
        "agree": s["oracle"]["agree"],
        "runs": s["oracle"]["runs"],
        "witnesses": f"{modes['values']} from the values mode and {modes['availability']} from "
        "availability",
        "strict_line": ", ".join(strict),
        "class_mean_line": ", ".join(
            f"{t} {100 * primary[t]['paired_site_class_mean']:.1f}%" for t in by_mean
        ),
        "beats": "\n".join(beats),
        "gap_a": gap["a"],
        "gap_b": gap["b"],
        "gap_mcnemar": f"{gap['p']:.2g}",
        "gap_template": _p3(gap["p_cluster_holm"]),
        "missed_l0": len(s["missed_l0"]),
        "l3_fps": ", ".join(
            f"{t} {l3[t]['k']}/{l3[t]['n']}" for t in sorted(l3, key=lambda t: -l3[t]["k"])[:2]
        ),
        "restatement_tool": restatement_tool,
        "restatement_k": restatement["k"],
        "restatement_n": restatement["n"],
        "n_immaterial": NUMBER_WORDS[sum(not x["material"] for x in classes.values())].lower(),
        "material_by_tool": ", ".join(
            [f"{order[0]} finds {found[order[0]]}"]
            + [f"{t} {found[t]}" for t in sorted(order[1:], key=lambda t: -found[t])]
        ),
        "material_any": impact["material_found_by_any"],
        "n_exact": NUMBER_WORDS[len(order) - len(inexact)].lower(),
        "inexact": _join(inexact),
        "chance_lo": f"{min(chance):.0f}",
        "chance_hi": f"{max(chance):.0f}",
    }
    return REPORT_FIGURES.format(**values).splitlines()


def readme_block(s: dict) -> str:
    values = _values(s)
    text = README_PROSE.format(**values)
    paragraphs = []
    for para in text.strip("\n").split("\n\n"):
        if para.startswith("- "):
            items = [" ".join(i.split()) for i in para.split("\n- ")]
            items = [i if i.startswith("- ") else "- " + i for i in items]
            wrap = textwrap.TextWrapper(96, subsequent_indent="  ", break_on_hyphens=False)
            paragraphs.append("\n".join(wrap.fill(i) for i in items))
        else:
            paragraphs.append(textwrap.fill(" ".join(para.split()), 96, break_on_hyphens=False))
    start, end = MARKERS
    return start + "\n\n".join(paragraphs) + "\n" + end


def render(s: dict) -> str:
    out = tables(s)
    out += ["", "## REPORT: figures in the prose", "", *(f"- {x}" for x in report_figures(s))]
    out += ["", "## README: headline prose", "", readme_block(s).rstrip("\n")]
    return "\n".join(out) + "\n"


def sync_readme(readme_text: str, block: str) -> str:
    start, end = MARKERS
    if (
        readme_text.count(start) != 1
        or readme_text.count(end) != 1
        or readme_text.index(start) > readme_text.index(end)
    ):
        raise ValueError("README.md needs exactly one block between the generated markers")
    head, rest = readme_text.split(start)
    return head + block + rest.split(end)[1]
